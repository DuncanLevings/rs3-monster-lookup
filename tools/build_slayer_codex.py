"""Build the bundled Slayer Codex reference from a saved Wiki article.

Usage: python tools/build_slayer_codex.py article.html YYYY-MM-DD
The build reads local HTML only. Review the output diff before publishing an update.
"""

import argparse
import json
import re
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote


class Node:
    def __init__(self, tag="", attrs=()):
        self.tag = tag
        self.attrs = dict(attrs)
        self.children = []

    def text(self):
        if self.tag == "sup":
            return ""
        if self.tag == "br":
            return " "
        return "".join(c if isinstance(c, str) else c.text() for c in self.children)

    def find(self, tag):
        result = []
        for child in self.children:
            if isinstance(child, Node):
                if child.tag == tag:
                    result.append(child)
                result.extend(child.find(tag))
        return result


class ArticleParser(HTMLParser):
    VOID = {"img", "br", "hr", "input", "meta", "link", "source", "wbr", "area", "col", "embed", "param"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node()
        self.stack = [self.root]

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in self.VOID:
            self.stack.append(node)

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, 0, -1):
            if self.stack[index].tag == tag:
                self.stack = self.stack[:index]
                break

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def clean(node):
    return " ".join(node.text().split())


def quote(text):
    return json.dumps(text, ensure_ascii=False)


def extract(html):
    parser = ArticleParser()
    parser.feed(html)
    tables = [t for t in parser.root.find("table") if "Altered Slayer" in t.text()[:1000]]
    if len(tables) != 1:
        raise ValueError("Expected one Slayer monster table")
    expected = ["No.", "Row, col", "Icon", "Monster options", "Location", "Slayer level",
                "Altered Slayer level", "Slayer XP (repeat)", "Dungeon size", "Assigned by"]
    records = []
    for index, row in enumerate(tables[0].find("tr")):
        cells = [c for c in row.children if isinstance(c, Node) and c.tag in ("td", "th")]
        if len(cells) != 10 or any("rowspan" in c.attrs or "colspan" in c.attrs for c in cells):
            raise ValueError("Unsupported table layout")
        if index == 0:
            if [clean(c) for c in cells] != expected:
                raise ValueError("Slayer table headers changed")
            continue
        number = int(clean(cells[0]))
        if number != len(records) + 1:
            raise ValueError("Non-sequential Codex numbers")
        pages = sorted({unquote(a.attrs["href"][3:].split("#")[0]).replace("_", " ")
                        for a in cells[3].find("a") if a.attrs.get("href", "").startswith("/w/")
                        and not a.attrs["href"].startswith("/w/Special:")
                        and "(Slayer_assignment)" not in a.attrs["href"]})
        references = {a.attrs["href"][1:] for a in cells[3].find("a")
                      if a.attrs.get("href", "").startswith("#cite_note")}
        notes = []
        for item in parser.root.find("li"):
            if item.attrs.get("id") in references:
                # Reference backlinks are separate children from the actual note.
                spans = [s for s in item.find("span") if s.attrs.get("class") == "reference-text"]
                if len(spans) != 1:
                    raise ValueError("Unsupported Codex note layout")
                notes.append(clean(spans[0]))
        records.append((number, pages, clean(cells[3]), clean(cells[5]), clean(cells[6]),
                        clean(cells[7]), clean(cells[8]), " ".join(notes)))
    if len(records) < 170:
        raise ValueError("Codex table appears incomplete")
    return records


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument("article", type=Path)
    args.add_argument("retrieved", help="Retrieval date, YYYY-MM-DD")
    options = args.parse_args()
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", options.retrieved):
        raise ValueError("Use an ISO retrieval date")
    html = options.article.read_text(encoding="utf-8")
    revision = re.search(r"oldid=(\d+)", html)
    if not revision:
        raise ValueError("Missing source revision")
    lines = ["-- Generated by tools/build_slayer_codex.py; update from the source, not by hand.",
             "-- RuneScape Wiki contributors, CC BY-NC-SA 3.0; see THIRD_PARTY_NOTICES.txt.",
             "return {", f"    retrieved = {quote(options.retrieved)},",
             f"    revision = {quote(revision[1])},", "    entries = {"]
    for number, pages, variants, level, altered, xp, size, notes in extract(html):
        lines.extend(["        {", f"            number = {number},",
                      "            pages = { " + ", ".join(map(quote, pages)) + " },",
                      *[f"            {key} = {quote(value)}," for key, value in
                        [("variants", variants), ("slayer_level", level), ("altered_level", altered),
                         ("soul_xp", xp), ("size", size), ("notes", notes)]], "        },"])
    lines.extend(["    },", "}", ""])
    target = Path(__file__).resolve().parent.parent / "src/data/slayer_codex_data.lua"
    target.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
